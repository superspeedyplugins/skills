#!/usr/bin/env python3
"""Build the bash script that repeats tested plugin updates on a live WordPress site.

Usage:
    python3 build_live_script.py manifest.json > update-live.sh

The manifest lists exactly the plugins that passed on staging (see SKILL.md, step 8). The
generated script never guesses: it refuses to run on any site but the manifest's live_url,
refuses to change anything unless every plugin is at its tested "from" version and every zip
matches its checksum, backs up the database, updates each plugin to exactly its "to" version and
stops at the first version that doesn't match. Standard library only.
"""

import json
import re
import shlex
import sys

SLUG = re.compile(r'^[a-z0-9][a-z0-9._-]*$')
VERSION = re.compile(r'^[0-9A-Za-z][0-9A-Za-z.+_-]*$')
SHA256 = re.compile(r'^[0-9a-f]{64}$')
URL = re.compile(r'^https?://[^\s\'"]+$')


class ManifestError(Exception):
    pass


def normalise_url(url):
    return url.rstrip('/')


def validate(manifest):
    if not isinstance(manifest, dict):
        raise ManifestError('The manifest must be a JSON object.')
    live = manifest.get('live_url')
    if not isinstance(live, str) or not URL.match(live):
        raise ManifestError('live_url must be the live site URL, for example https://example.com.')
    tested = manifest.get('tested_on', '')
    if tested and normalise_url(str(tested)) == normalise_url(live):
        raise ManifestError('tested_on is the same URL as live_url. The updates must be tested on staging.')
    plugins = manifest.get('plugins')
    if not isinstance(plugins, list) or not plugins:
        raise ManifestError('plugins must be a non-empty list.')
    seen = set()
    for i, p in enumerate(plugins, 1):
        where = 'plugins[%d]' % i
        if not isinstance(p, dict):
            raise ManifestError(where + ' must be an object.')
        slug = p.get('slug')
        if not isinstance(slug, str) or not SLUG.match(slug):
            raise ManifestError(where + ': slug must be a plugin folder name such as woocommerce.')
        if slug in seen:
            raise ManifestError(where + ': ' + slug + ' is listed twice.')
        seen.add(slug)
        for key in ('from', 'to'):
            v = p.get(key)
            if not isinstance(v, str) or not VERSION.match(v):
                raise ManifestError(where + ': ' + key + ' must be an exact version such as 10.3.0.')
        if p['from'] == p['to']:
            raise ManifestError(where + ': from and to are the same version.')
        source = p.get('source')
        if source == 'wordpress.org':
            if 'zip' in p:
                raise ManifestError(where + ': a wordpress.org plugin takes no zip.')
        elif source == 'zip':
            z = p.get('zip')
            if not isinstance(z, str) or not z or '/' in z or '\\' in z or z.startswith('.'):
                raise ManifestError(where + ': zip must be a file name in the same folder as the script.')
            if not isinstance(p.get('sha256'), str) or not SHA256.match(p['sha256']):
                raise ManifestError(where + ': sha256 must be the 64-character checksum of the zip tested on staging.')
        else:
            raise ManifestError(where + ': source must be "wordpress.org" or "zip".')
    return manifest


def build(manifest):
    validate(manifest)
    q = shlex.quote
    live = normalise_url(manifest['live_url'])
    tested = manifest.get('tested_on', '')
    plugins = manifest['plugins']
    out = []
    w = out.append
    w('#!/usr/bin/env bash')
    w('# Repeats plugin updates tested on staging%s on the live site %s.' % (
        (' (' + str(tested) + ')') if tested else '', live))
    w('# Generated by the plugin-updates skill (build_live_script.py). Do not edit by hand.')
    w('# Run from the live site\'s WordPress folder. --check runs the checks only and changes nothing.')
    w('set -euo pipefail')
    w('')
    w('CHECK_ONLY=0')
    w('if [ "${1:-}" = "--check" ]; then CHECK_ONLY=1; elif [ -n "${1:-}" ]; then echo "Unknown option: $1" >&2; exit 2; fi')
    w('SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"')
    w('WP="${WP:-wp}"')
    w('LIVE_URL=%s' % q(live))
    w('')
    w('fail() { echo "STOPPED: $*" >&2; exit 1; }')
    w('sha256_of() { if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d" " -f1; else shasum -a 256 "$1" | cut -d" " -f1; fi; }')
    w('')
    w('command -v "$WP" >/dev/null 2>&1 || fail "WP-CLI ($WP) is not on PATH."')
    w('SITEURL="$("$WP" option get siteurl)" || fail "WP-CLI could not read siteurl. Run this from the live site\'s WordPress folder."')
    w('[ "${SITEURL%/}" = "$LIVE_URL" ] || fail "This site is $SITEURL, not $LIVE_URL. Nothing was changed."')
    w('echo "Site: $SITEURL"')
    w('')
    w('PROBLEMS=0')
    w('check_version() {')
    w('  local slug="$1" want="$2" have')
    w('  if ! have="$("$WP" plugin get "$slug" --field=version 2>/dev/null)"; then')
    w('    echo "  $slug: not installed, expected $want"; PROBLEMS=$((PROBLEMS+1)); return')
    w('  fi')
    w('  if [ "$have" = "$want" ]; then echo "  $slug: $have, as tested"; else echo "  $slug: $have, but staging was tested from $want"; PROBLEMS=$((PROBLEMS+1)); fi')
    w('}')
    w('check_zip() {')
    w('  local file="$SCRIPT_DIR/$1" want="$2"')
    w('  if [ ! -f "$file" ]; then echo "  $1: missing, copy it next to this script"; PROBLEMS=$((PROBLEMS+1)); return; fi')
    w('  if [ "$(sha256_of "$file")" = "$want" ]; then echo "  $1: checksum matches the zip tested on staging"; else echo "  $1: checksum does not match the zip tested on staging"; PROBLEMS=$((PROBLEMS+1)); fi')
    w('}')
    w('')
    w('echo "Checking installed versions:"')
    for p in plugins:
        w('check_version %s %s' % (q(p['slug']), q(p['from'])))
    zips = [p for p in plugins if p['source'] == 'zip']
    if zips:
        w('echo "Checking zips:"')
        for p in zips:
            w('check_zip %s %s' % (q(p['zip']), q(p['sha256'])))
    w('[ "$PROBLEMS" -eq 0 ] || fail "$PROBLEMS check(s) failed. Nothing was changed."')
    w('if [ "$CHECK_ONLY" -eq 1 ]; then echo "All checks passed. Nothing was changed (--check)."; exit 0; fi')
    w('')
    w('BACKUP="${BACKUP_DIR:-$HOME}/before-plugin-updates-$(date +%Y-%m-%d-%H%M%S).sql"')
    w('echo "Backing up the database to $BACKUP"')
    w('"$WP" db export "$BACKUP"')
    w('')
    w('rollback_help() {')
    w('  echo')
    w('  echo "To roll back, run whichever of these apply:"')
    for p in plugins:
        if p['source'] == 'wordpress.org':
            w('  echo %s' % q('  %s plugin install %s --version=%s --force' % ('wp', p['slug'], p['from'])))
        else:
            w('  echo %s' % q('  %s plugin install <the %s %s zip> --force' % ('wp', p['slug'], p['from'])))
    w('  echo "  wp db import $BACKUP    (undoes database changes the new versions made)"')
    w('}')
    w('trap \'status=$?; if [ "$status" -ne 0 ]; then rollback_help; fi\' EXIT')
    w('')
    w('verify() {')
    w('  local slug="$1" want="$2" have')
    w('  have="$("$WP" plugin get "$slug" --field=version)"')
    w('  [ "$have" = "$want" ] || fail "$slug is at $have after the update, not $want. Stopped before the next plugin."')
    w('  echo "  $slug: now $have"')
    w('}')
    w('')
    for p in plugins:
        slug, to = q(p['slug']), q(p['to'])
        if p['source'] == 'wordpress.org':
            w('echo "Updating %s to %s"' % (p['slug'], p['to']))
            w('"$WP" plugin update %s --version=%s' % (slug, to))
        else:
            w('echo "Installing %s %s from %s"' % (p['slug'], p['to'], p['zip']))
            w('"$WP" plugin install "$SCRIPT_DIR"/%s --force' % q(p['zip']))
        w('verify %s %s' % (slug, to))
    w('')
    w('rollback_help')
    w('echo')
    w('echo "Done. For the next day or two, time the home page, busiest category, a product page,"')
    w('echo "the cart and the checkout, and read the PHP error log for anything new since now: $(date)."')
    return '\n'.join(out) + '\n'


def main(argv):
    if len(argv) != 2:
        sys.stderr.write('Usage: python3 build_live_script.py manifest.json > update-live.sh\n')
        return 2
    try:
        with open(argv[1], encoding='utf-8') as fh:
            manifest = json.load(fh)
        sys.stdout.write(build(manifest))
    except (OSError, ValueError, ManifestError) as e:
        sys.stderr.write('build_live_script: %s\n' % e)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))

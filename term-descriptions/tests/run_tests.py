#!/usr/bin/env python3
"""Tests for scripts/term_csv.py. Run: python3 tests/run_tests.py

Every test drives the real script as a subprocess, the way the skill uses it, and checks the
result with Python's own csv module or with exact byte comparisons against the fixture files,
never with the script's own parser.

Fixtures (tests/fixtures/):
  real-export-100.csv          100 product_cat rows written by Super Speedy Imports' own term export
                               (superspeedyimports_data_term_export) on the add-on's synthetic test
                               site, with two termmeta columns. Includes an embedded newline.
  addon-sample-30.csv          30 rows in the same format plus the add-on's ssitd_findings,
                               ssitd_group and ssitd_group_text columns. Synthetic outdoor-shop data.
  edge-cases.csv               Formula-escaped cells, embedded LF and CRLF, commas, quotes,
                               unicode, spaces-only and tab cells.
  edge-cases-crlf-bom.csv      The same records with a UTF-8 BOM and CRLF record endings.
  edge-cases-no-final-newline.csv  The same records without a newline after the last one.
make_fixtures.py regenerates the last four. The real export is not regenerated by it.
"""
import csv
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
FIX = os.path.join(HERE, 'fixtures')
SCRIPT = os.path.join(HERE, '..', 'scripts', 'term_csv.py')
ALL_FIXTURES = ['real-export-100.csv', 'addon-sample-30.csv', 'edge-cases.csv',
                'edge-cases-crlf-bom.csv', 'edge-cases-no-final-newline.csv']
DESC = 'term_taxonomy.description'


def run(*args):
    p = subprocess.run([sys.executable, SCRIPT] + [str(a) for a in args],
                       capture_output=True, text=True, encoding='utf-8')
    return p.returncode, p.stdout, p.stderr


def fixture(name):
    return os.path.join(FIX, name)


def read_bytes(path):
    with open(path, 'rb') as f:
        return f.read()


def rows_of(path):
    """Independent parse with the csv module: (header, [row, ...])."""
    with open(path, encoding='utf-8-sig', newline='') as f:
        rows = list(csv.reader(f))
    return rows[0], rows[1:]


def write_rows(path, header, rows, bom=False, eol='\r\n'):
    with open(path, 'w', encoding='utf-8-sig' if bom else 'utf-8', newline='') as f:
        w = csv.writer(f, lineterminator=eol)
        w.writerow(header)
        w.writerows(rows)


def jsonl(path, entries):
    with open(path, 'w', encoding='utf-8') as f:
        for e in entries:
            f.write(json.dumps(e, ensure_ascii=False) + '\n')


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix='term-csv-test-')

    def tearDown(self):
        # Scratch copies only; the fixtures themselves are never touched.
        shutil.rmtree(self.tmp, ignore_errors=True)

    def path(self, name):
        return os.path.join(self.tmp, name)


class Inspect(Base):
    def test_addon_sample_summary(self):
        code, out, err = run('inspect', fixture('addon-sample-30.csv'), '--json')
        self.assertEqual(code, 0, err)
        data = json.loads(out)
        self.assertEqual(data['rows'], 30)
        self.assertEqual(data['taxonomies'], {'product_cat': 30})
        self.assertEqual(data['source_sites'], {'https://shop.example.com': 30})
        self.assertTrue(data['has_addon_columns'])
        f = data['findings']
        self.assertEqual((f['template'], f['boilerplate'], f['missing'], f['near_duplicate'],
                          f['placeholder'], f['name_only'], f['duplicate'], f['short']),
                         (8, 5, 4, 3, 3, 2, 3, 10))
        groups = {g['group']: g for g in data['groups']}
        self.assertEqual(groups['template-7c1e2a']['size'], 8)
        self.assertEqual(groups['template-7c1e2a']['text'],
                         'Shop our range of {name} at great prices. Free UK delivery on orders over £50.')
        self.assertEqual(data['groups'][0]['group'], 'template-7c1e2a')  # largest first
        self.assertEqual(data['empty_descriptions'], 4)

    def test_real_export_without_addon_columns(self):
        code, out, err = run('inspect', fixture('real-export-100.csv'), '--json')
        self.assertEqual(code, 0, err)
        data = json.loads(out)
        self.assertEqual(data['rows'], 100)
        self.assertFalse(data['has_addon_columns'])
        self.assertEqual(data['extra_columns'], ['termmeta.display_type', 'termmeta.zzd_seo_title'])

    def test_bom_and_line_endings_reported(self):
        code, out, err = run('inspect', fixture('edge-cases-crlf-bom.csv'), '--json')
        self.assertEqual(code, 0, err)
        data = json.loads(out)
        self.assertTrue(data['bom'])
        self.assertEqual(data['line_ending'], 'CRLF')
        self.assertEqual(data['rows'], 8)

    def test_human_output_mentions_counts(self):
        code, out, err = run('inspect', fixture('addon-sample-30.csv'))
        self.assertEqual(code, 0, err)
        self.assertIn('30 rows', out)
        self.assertIn('template-7c1e2a', out)

    def test_not_a_term_export(self):
        p = self.path('bad.csv')
        with open(p, 'w', encoding='utf-8', newline='') as f:
            f.write('ID,post_title\n1,Hello\n')
        code, out, err = run('inspect', p)
        self.assertEqual(code, 2)
        self.assertIn('term_taxonomy.description', err)

    def test_unterminated_quote_is_an_error(self):
        p = self.path('broken.csv')
        raw = read_bytes(fixture('edge-cases.csv')).decode('utf-8')
        with open(p, 'w', encoding='utf-8', newline='') as f:
            f.write(raw + '209,product_tag,x,"never closed\n')
        code, out, err = run('inspect', p)
        self.assertEqual(code, 2)
        self.assertIn('quote', err.lower())


class Show(Base):
    def test_group_filter(self):
        code, out, err = run('show', fixture('addon-sample-30.csv'), '--group', 'template-7c1e2a')
        self.assertEqual(code, 0, err)
        items = [json.loads(l) for l in out.splitlines()]
        self.assertEqual(len(items), 8)
        self.assertEqual(items[0]['term_id'], '121')
        self.assertEqual(items[0]['name'], 'Waterproof Jackets')
        self.assertEqual(items[0]['parent_path'], 'Clothing > Jackets > Waterproof Jackets')
        self.assertEqual(items[0]['findings'], 'template')
        self.assertIn('Waterproof Jackets', items[0]['description'])

    def test_offset_limit_and_done(self):
        done = self.path('rewrites.jsonl')
        jsonl(done, [{'term_id': 101, 'description': '<p>x</p>'}, {'term_id': 102, 'keep': True}])
        code, out, err = run('show', fixture('addon-sample-30.csv'), '--limit', '5', '--done', done)
        self.assertEqual(code, 0, err)
